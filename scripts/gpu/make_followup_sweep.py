"""Write configs/sweeps/followup_f1.yaml: follow-up F1 on the learning failure (F43, F48, F49).

    uv run python scripts/gpu/make_followup_sweep.py     # rewrites the sweep file

Exploratory; scope and GPU launch pending the owner (Q19). Condition C's task, 5 seeds, four arms:
- C        control: the session-S condition, retrained at this commit (same code as the arms)
- C_ft     fine-tuned from A's final checkpoint (same seed), Li & Sun's protocol
- C_r40    from scratch, action delay U{0..40 ms}
- C_hcrit  from scratch, critic also sees the 5 actions sent before the last one
Round-robin by seed, so a cut leaves balanced arms. Full in-job eval grid (same episodes
as session S), no probing traces. Backend fixed to jax (session S's pick, F-ledger).
Before launching: push_code.sh, push_init.sh (A checkpoints), bootstrap.sh.
"""

from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "configs" / "sweeps" / "followup_f1.yaml"
ARMS = ["C", "followup/C_ft", "followup/C_r40", "followup/C_hcrit"]
SEEDS = range(5)
MIN_PER_RUN = 9.0  # session S: ≈ 430 s training + 106 s eval grid per MLP run (ledger)

N_RUNS = len(ARMS) * len(SEEDS)
HEADER = f"""\
# Follow-up F1 (exploratory, Q19): why C never learns to walk. GENERATED by
# scripts/gpu/make_followup_sweep.py; edit that script, not this file.
# {N_RUNS} runs x ~{MIN_PER_RUN:.0f} min ~ {N_RUNS * MIN_PER_RUN / 60:.1f} GPU h (session-S speed).
"""


def _line(d: dict) -> str:
    return "  - " + json.dumps(d)


def lines() -> list[str]:
    out = ["jobs:"]
    out.append("  # Fine-tune sources must be on the box (scripts/gpu/push_init.sh)")
    out.append(
        _line(
            {
                "step": "ls "
                + " ".join(f"runs/A_mlp_s{s}_4a4a467/checkpoints/it001221.msgpack" for s in SEEDS)
            }
        )
    )
    for seed in SEEDS:
        for arm in ARMS:
            out.append(_line({"experiment": arm, "seeds": [seed], "overrides": ["env.impl=jax"]}))
    return out


def main() -> None:
    OUT.write_text(HEADER + "\n".join(lines()) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
