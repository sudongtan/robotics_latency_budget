"""Write configs/sweeps/session_s.yaml: the single GPU session in priority tiers (D27, D36).

    uv run python scripts/gpu/make_session_sweep.py     # rewrites the sweep file

Order (owner's choice, D36). Each tier is a complete package; inside a tier, jobs go round by
round (one seed of every condition per round), so a cut anywhere leaves balanced seed counts.

- backend benchmark → pick backend → cost cap (may trim later tiers, D35/D36)
- tier 0  calibration: Brax on our env ×2, A ×2, Brax on Playground's env ×1, C/D/E ×1 → GATE
- tier 1  core to 5 seeds: A, C, D, E, F and observation-delay C/D/E (every hypothesis H1–H6
          testable at the pre-registered minimum)
- tier 2  C, D, E, F seeds 5–9 (the pre-registered 10 seeds for the main comparisons)
- tier 3  B20, B40, B60 × 5 (fixed-delay specialist reference curves)
- tier 4  exploratory: motor-lag C/D/E × 5, history length H = 2, 8 × 3

Probing traces on seeds 0–4 of A, C, D, E, F. Every training job gets env.impl=@IMPL@.
"""

from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "configs" / "sweeps" / "session_s.yaml"
TRACES = "mjx_eval.traces.enabled=true"
TRACED = {"A", "C", "D", "E", "F"}
CAP_HOURS = 50

HEADER = """\
# Session S: the single GPU rental (D27), in priority tiers (D36).
# GENERATED by scripts/gpu/make_session_sweep.py; edit that script, not this file.
# A cut at any point leaves complete tiers / balanced seed rounds:
#   tier 0 calibration + gate (~3 h) | tier 1 core x5 incl. obs-delay (~16 h) |
#   tier 2 C-F seeds 5-9 (~23 h) | tier 3 B specialists (~28 h) | tier 4 exploratory (~36 h)
#   (cumulative hours at an assumed 200k env-steps/s; the cost cap uses the measured speed)
"""


def _line(d: dict) -> str:
    return "  - " + json.dumps(d)


def _run(exp: str, seed: int) -> str:
    over = ["env.impl=@IMPL@"]
    if exp in TRACED and seed < 5:
        over.append(TRACES)
    name = exp if exp in {"A", "B20", "B40", "B60", "C", "D", "E", "F"} else f"ablations/{exp}"
    return _line({"experiment": name, "seeds": [seed], "overrides": over})


def lines() -> list[str]:
    out = ["jobs:"]
    out.append("  # --- MJX backend benchmark (D3): 20M steps of A per backend, no eval grid")
    for impl in ("jax", "warp"):
        out.append(
            _line(
                {
                    "experiment": "A",
                    "seeds": [0],
                    "overrides": [
                        f"env.impl={impl}",
                        "train.total_steps=2e7",
                        "train.num_evals=1",
                        "mjx_eval.enabled=false",
                        f"train.run_prefix=bench_{impl}_",
                    ],
                }
            )
        )
    out.append(_line({"step": "uv run python scripts/gpu/pick_backend.py @LOGDIR@/impl"}))
    out.append(
        "  # Cost cap (D35/D36): runs only the tiers that fit in --max-hours at the measured speed"
    )
    out.append(
        _line(
            {
                "step": "uv run python scripts/gpu/cost_cap.py configs/sweeps/session_s.yaml "
                f"@LOGDIR@/impl --max-hours {CAP_HOURS}"
            }
        )
    )

    out.append(_line({"tier": 0, "label": "calibration + gate"}))
    brax = "scripts/brax_reference.py"
    out.append(_line({"script": brax, "seeds": [0, 1], "overrides": ["env=ours", "impl=@IMPL@"]}))
    done = set()
    for exp, seed in (("A", 0), ("A", 1)):
        out.append(_run(exp, seed))
        done.add((exp, seed))
    out.append(_line({"script": brax, "seeds": [0], "overrides": ["env=upstream", "impl=@IMPL@"]}))
    for exp in ("C", "D", "E"):
        out.append(_run(exp, 0))
        done.add((exp, 0))
    out.append(_line({"gate": "uv run python scripts/gpu/gate.py"}))

    tiers = [
        (
            1,
            "core to 5 seeds: A, C, D, E, F + obs-delay C/D/E",
            [(s, ["A", "C", "D", "E", "F", "C_obs", "D_obs", "E_obs"]) for s in range(5)],
        ),
        (2, "C, D, E, F seeds 5-9", [(s, ["C", "D", "E", "F"]) for s in range(5, 10)]),
        (3, "B20, B40, B60 x 5", [(s, ["B20", "B40", "B60"]) for s in range(5)]),
        (
            4,
            "exploratory: motor-lag C/D/E x 5, history length 2/8 x 3",
            [(s, ["C_tm", "D_tm", "E_tm"] + (["DH2", "DH8"] if s < 3 else [])) for s in range(5)],
        ),
    ]
    for n, label, rounds in tiers:
        out.append(_line({"tier": n, "label": label}))
        for seed, exps in rounds:
            out += [_run(e, seed) for e in exps if (e, seed) not in done]
    return out


def main() -> None:
    OUT.write_text(HEADER + "\n".join(lines()) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
